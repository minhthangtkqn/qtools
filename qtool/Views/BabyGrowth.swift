/// All 7 WHO z-score columns for weight (kg) and height/length (cm).
/// Custom positional init keeps data rows compact.
struct GrowthStat {
    // Weight (kg): -3 SD … +3 SD
    let weightMinus3SD: Double
    let weightMinus2SD: Double
    let weightMinus1SD: Double
    let weightMedian:   Double
    let weightPlus1SD:  Double
    let weightPlus2SD:  Double
    let weightPlus3SD:  Double
    // Height/Length (cm): -3 SD … +3 SD
    let heightMinus3SD: Double
    let heightMinus2SD: Double
    let heightMinus1SD: Double
    let heightMedian:   Double
    let heightPlus1SD:  Double
    let heightPlus2SD:  Double
    let heightPlus3SD:  Double

    // Positional init so data rows stay on one line
    init(_ wm3: Double, _ wm2: Double, _ wm1: Double, _ w0: Double, _ wp1: Double, _ wp2: Double, _ wp3: Double,
         _ hm3: Double, _ hm2: Double, _ hm1: Double, _ h0: Double, _ hp1: Double, _ hp2: Double, _ hp3: Double) {
        weightMinus3SD = wm3; weightMinus2SD = wm2; weightMinus1SD = wm1; weightMedian = w0
