// MARK: - View

struct BabyGrowthView: View {
    @State private var timeMode:     TimeMode = .month
    @State private var selectedMonth: Int = 0
    @State private var selectedWeek:  Int = 0
    @State private var sex:           BabySex = .boy

    private var stat: GrowthStat {
        switch timeMode {
        case .month: return sex == .boy ? boyMonthly[selectedMonth] : girlMonthly[selectedMonth]
        case .week:  return sex == .boy ? boyWeekly[selectedWeek]   : girlWeekly[selectedWeek]
        }
    }

    var body: some View {
        VStack(spacing: 20) {
            Text("Baby Growth").font(.title).fontWeight(.bold)

            Picker("Mode", selection: $timeMode) {
                ForEach(TimeMode.allCases, id: \.self) { Text($0.rawValue).tag($0) }
            }
            .pickerStyle(.segmented)
            .padding(.horizontal, 24)

            HStack(spacing: 12) {
                Text(timeMode == .month ? "Month" : "Week").fontWeight(.semibold)
                if timeMode == .month {
                    Picker("Month", selection: $selectedMonth) {
                        ForEach(0..<boyMonthly.count, id: \.self) { Text("\($0)").tag($0) }
                    }.pickerStyle(.wheel).frame(maxWidth: 100)
                } else {
                    Picker("Week", selection: $selectedWeek) {
                        ForEach(0..<boyWeekly.count, id: \.self) { Text("\($0)").tag($0) }
                    }.pickerStyle(.wheel).frame(maxWidth: 100)
                }
                Toggle(isOn: Binding(
                    get: { sex == .boy },
                    set: { sex = $0 ? .boy : .girl }
                )) {
                    Text(sex == .boy ? "Boy" : "Girl")
                }
                .toggleStyle(.switch)
                .frame(maxWidth: 120)
            }
            .padding(.horizontal, 20)

            VStack(alignment: .leading, spacing: 8) {
                let index = timeMode == .month ? selectedMonth : selectedWeek
                Text("\(timeMode.rawValue) \(index) — \(sex.rawValue.capitalized)")
                    .fontWeight(.semibold)
                Text("Weight: \(String(format: "%.1f", stat.weightMinus2SD)) kg — \(String(format: "%.1f", stat.weightPlus2SD)) kg")
                    .font(.title3)
                Text("Height: \(String(format: "%.1f", stat.heightMinus2SD)) cm — \(String(format: "%.1f", stat.heightPlus2SD)) cm")
                    .font(.title3)
            }
            .padding(20)
            .frame(maxWidth: .infinity, alignment: .leading)

            Spacer()
        }
        .padding(.top, 20)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(Color(.systemBackground))
    }
}
